import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }
>(({ className, hoverable = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[var(--radius-md)] border border-[var(--border)] bg-[var(--surface)] p-5 text-[var(--foreground)] transition-colors duration-150",
      hoverable &&
        "hover:border-[var(--border-hover)] hover:bg-[var(--surface-hover)] hover:-translate-y-[2px] transition-all duration-150 cursor-pointer",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

